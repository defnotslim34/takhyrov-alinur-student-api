# Determine project directory relative to script location
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
LOG_DIR="$PROJECT_ROOT/logs"
LOG_FILE="$LOG_DIR/Takhyrov_Alinur_system_report.log"

# Ensure logs directory exists
mkdir -p "$LOG_DIR"

# Generate Report
generate_report() {
    echo "============================================================"
    echo "               SYSTEM MONITORING REPORT                     "
    echo "============================================================"
    echo "Student Full Name : Alinur Takhyrov"
    echo "Student ID        : 38110"
    echo "GitHub Nickname   : defnotslim34"
    echo "Report Generated  : $(date '+%Y-%m-%d %H:%M:%S %Z')"
    echo "Current Username  : $(whoami 2>/dev/null || echo "$USER")"
    echo "Hostname          : $(hostname 2>/dev/null || echo "localhost")"
    echo "------------------------------------------------------------"
    echo "OPERATING SYSTEM & KERNEL:"
    if [ -f /etc/os-release ]; then
        . /etc/os-release
        echo "OS Name           : $PRETTY_NAME"
    elif command -v sw_vers >/dev/null 2>&1; then
        echo "OS Name           : $(sw_vers -productName) $(sw_vers -productVersion)"
    else
        echo "OS Name           : $(uname -s)"
    fi
    echo "Kernel Version    : $(uname -r)"
    echo "Architecture      : $(uname -m)"
    echo "------------------------------------------------------------"
    echo "CPU INFORMATION:"
    if command -v lscpu >/dev/null 2>&1; then
        lscpu | grep -E "Model name|CPU\(s\):|Thread\(s\) per core|Core\(s\) per socket" || true
    elif [ -f /proc/cpuinfo ]; then
        grep -m 1 "model name" /proc/cpuinfo || true
        echo "CPU Cores         : $(nproc 2>/dev/null || grep -c '^processor' /proc/cpuinfo)"
    else
        echo "Processor Architecture: $(uname -p 2>/dev/null || echo "x86_64")"
    fi
    echo "------------------------------------------------------------"
    echo "MEMORY INFORMATION:"
    if command -v free >/dev/null 2>&1; then
        free -h
    elif [ -f /proc/meminfo ]; then
        grep -E "MemTotal|MemFree|MemAvailable" /proc/meminfo
    else
        echo "Memory statistics available via system metrics."
    fi
    echo "------------------------------------------------------------"
    echo "DISK USAGE & AVAILABLE DISK SPACE:"
    if command -v df >/dev/null 2>&1; then
        df -h / 2>/dev/null || df -h
        echo "Available space on root (/): $(df -h / 2>/dev/null | awk 'NR==2 {print $4}' || echo "N/A")"
    fi
    echo "============================================================"
    echo "Report saved to: $LOG_FILE"
    echo "Status: SUCCESS - Generated by Alinur Takhyrov (ID: 38110)"
    echo "============================================================"
}

# Display report on terminal and append to student log file
generate_report | tee -a "$LOG_FILE"
